#!/usr/bin/env python3
"""Builds the PREPARED demo meeting: a synthesized audio file (espeak-ng, robotic
voices, clearly not a real meeting) and its transcript whose timestamps are taken
from the real duration of each synthesized line. Both are fictional and labelled
as prepared demo material (ADR-0014). Re-run after editing LINES:
    python3 scripts/make-demo-meeting.py
Needs espeak-ng and ffmpeg. Writes docs/demo/planerka-demo.ogg and .txt and
web/src/lib/demoMeeting.ts."""
import json, os, subprocess, tempfile

LINES = [
    ("Олег Киселев", "ru+m3", "Начинаем планёрку склада. Запись идёт, все дали согласие."),
    ("Асель Темирова", "ru+f3", "Этикетки приходится печатать на отдельном компьютере, на каждую машину уходит три-четыре минуты."),
    ("Руслан Исаев", "ru+m1", "Сканер у ворот номер два зависает на холоде, вводим коды вручную."),
    ("Асель Темирова", "ru+f3", "Предлагаю печатать этикетку прямо со сканера на мобильный принтер у ворот."),
    ("Руслан Исаев", "ru+m1", "Я против, если не будет запасного принтера: иначе встанет приёмка."),
    ("Олег Киселев", "ru+m3", "Выяснилось, что чаще всего задержки на приёмке именно из-за этикеток."),
    ("Дмитрий Орлов", "ru+m7", "Кто будет закупать запасной принтер, пока не решили."),
    ("Олег Киселев", "ru+m3", "Решили: пилот печати этикеток со сканера у ворот номер один, ответственный: Дмитрий Орлов, срок до пятницы."),
]
GAP = 0.7
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tmp = tempfile.mkdtemp()
parts, lines, t = [], [], 0.0
for i, (who, voice, text) in enumerate(LINES):
    wav = os.path.join(tmp, f"{i}.wav")
    subprocess.run(["espeak-ng", "-v", voice, "-s", "160", "-w", wav, text], check=True)
    dur = float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", wav], capture_output=True, text=True, check=True).stdout)
    s = int(t)
    lines.append(f"[{s // 60:02d}:{s % 60:02d}] {who}: {text}")
    # Pad so the next line starts exactly at t + dur + GAP; the stamp is floored to the second, so it never points past the start.
    parts.append((wav, dur))
    t += dur + GAP
listfile = os.path.join(tmp, "list.txt")
sil = os.path.join(tmp, "sil.wav")
subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-f", "lavfi", "-i", "anullsrc=r=22050:cl=mono", "-t", str(GAP), sil], check=True)
with open(listfile, "w") as f:
    for wav, _ in parts:
        f.write(f"file '{wav}'\nfile '{sil}'\n")
out_ogg = os.path.join(root, "docs/demo/planerka-demo.ogg")
subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-f", "concat", "-safe", "0", "-i", listfile, "-ar", "24000", "-ac", "1", "-c:a", "libopus", "-b:a", "24k", out_ogg], check=True)
transcript = "\n".join(lines)
with open(os.path.join(root, "docs/demo/planerka-demo.txt"), "w") as f:
    f.write(transcript + "\n")
with open(os.path.join(root, "web/src/lib/demoMeeting.ts"), "w") as f:
    f.write("// Generated by scripts/make-demo-meeting.py — do not edit by hand.\n")
    f.write("/** PREPARED demo transcript (fictional people, synthesized voices). Always shown with the «подготовленная» label. */\n")
    f.write(f"export const DEMO_TRANSCRIPT = {json.dumps(transcript, ensure_ascii=False)};\n")
print(f"{t:.1f} s audio, {os.path.getsize(out_ogg)} bytes")
print(transcript)
